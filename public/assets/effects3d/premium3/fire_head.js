function update(g2, bs, t, h) {
  const U = g2.userData;
  if (!U.frame) return;
  const dt = U.tick.tick(t);
  U.frame.update(dt);
  U.world.userData.sync();
  const e = U.expr.update(bs, dt, h);
  const rage = clamp(Math.max(e.browDown, (e.jaw - 0.35) / 0.5));
  U.pow = damp(U.pow, 0.62 + rage * 0.55, rage > U.pow - 0.62 ? 9 : 2.5, dt);
  if (!U.frame.attached && !U.showcase) {
    U.showcase = true;
    for (let i = 0; i < 40; i++) {
      spawnEmber(U, 1);
      U.embers.update(0.03, U.down);
    }
    for (let i = 0; i < 4; i++) {
      spawnSmoke(U);
      U.smoke.update(0.4, U.down);
    }
  }
  const up = U.frame.up;
  const flick = 1 + Math.sin(t * 17) * 0.03 + Math.sin(t * 23.7) * 0.02;
  for (const Lr of U.layers) {
    const u = Lr.mat.uniforms;
    u.uTime.value = t * Lr.sp;
    u.uPow.value = 1.25 - U.pow * 0.45;
    u.uUp.value.copy(up).lerp(U.up, 0.25).normalize().multiplyScalar(0.72).addScaledVector(Lr.out, 0.28).normalize();
    u.uUp.value.applyQuaternion(U.frame.q);
    u.uSize.value.set(Lr.w * (0.85 + U.pow * 0.3), Lr.hh * (0.75 + U.pow * 0.45) * flick);
    u.uCenter.value.copy(Lr.base);
  }
  U.accE += dt * (10 + rage * 40);
  while (U.accE >= 1) {
    spawnEmber(U, 0.6 + rage);
    U.accE -= 1;
  }
  U.accS += dt * (1.2 + rage * 1.5);
  while (U.accS >= 1) {
    spawnSmoke(U);
    U.accS -= 1;
  }
  U.embers.update(dt, U.down);
  U.smoke.update(dt, U.down);
}
