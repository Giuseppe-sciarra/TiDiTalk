function blowOut(U) {
  const r = U.rnd;
  U.cake.updateMatrix();
  for (const C of U.candles) {
    C.lit = 0;
    C.relight = 3.6 + r() * 0.8;
    C.smoke = 1.6;
  }
  const p = U.v.set(0, 10, 0).applyMatrix4(U.cake.matrix);
  U.frame.toWorld(p, p);
  for (let i = 0; i < 90; i++) {
    const d = U.d.set((r() < 0.5 ? -1 : 1) * (0.45 + r() * 0.95), 0.9 + r() * 0.8, 0.2 + (r() - 0.5) * 1).normalize();
    const sp = 45 + r() * 70;
    U.conf.spawn((__s0["x"] = p.x, __s0["y"] = p.y, __s0["z"] = p.z, __s0["vx"] = d.x * sp, __s0["vy"] = d.y * sp, __s0["vz"] = d.z * sp, __s0["life"] = 3 + r(), __s0["s"] = 1.1 + r() * 0.5, __s0["q"] = randQuat(r), __s0["wx"] = (r() - 0.5) * 20, __s0["wy"] = (r() - 0.5) * 20, __s0["wz"] = (r() - 0.5) * 20, __s0["drag"] = 3.4, __s0["grav"] = 140, __s0["flut"] = 12, __s0["color"] = U.cols[r() * U.cols.length | 0], __s0["grow"] = 0.05, __s0));
  }
  for (let i = 0; i < 16; i++) {
    const a = r() * 6.28, sp = 30 + r() * 50;
    U.fx.spawn((__s1["x"] = p.x, __s1["y"] = p.y, __s1["z"] = p.z, __s1["vx"] = Math.cos(a) * sp, __s1["vy"] = Math.abs(Math.sin(a)) * sp + 10, __s1["life"] = 0.7, __s1["size"] = 1.3 + r() * 1.3, __s1["size1"] = 0.2, __s1["r"] = 1, __s1["g"] = 0.85, __s1["b"] = 0.4, __s1["a"] = 1, __s1["cell"] = U.atlas.cell.star, __s1["spin"] = 5, __s1["drag"] = 3, __s1["grav"] = 50, __s1["fadeIn"] = 0.05, __s1["fadeOut"] = 0.5, __s1));
  }
  U.bob.v += 6;
}
function anyLit(U) {
  for (const C of U.candles) if (C.lit > 0.5) return true;
  return false;
}
function update(g2, bs, t, h) {
  const U = g2.userData;
  if (!U.frame) return;
  const dt = U.tick.tick(t);
  U.frame.update(dt);
  U.world.userData.sync();
  const e = U.expr.update(bs, dt, h);
  if (U.trig.update(e.pucker, dt) && anyLit(U)) blowOut(U);
  if (!U.frame.attached && !U.showcase) {
    U.showcase = true;
  }
  const b = U.bob.step(dt, 0);
  U.cake.position.y = -17.5 + Math.sin(t * 1.4) * 0.35 + b * 0.3;
  U.cake.rotation.y = Math.sin(t * 0.6) * 0.2;
  U.tinsel.rotation.y = t * 0.6;
  U.cake.updateMatrix();
  U.flames.clear();
  const r = U.rnd;
  for (const C of U.candles) {
    if (C.lit < 1 && C.relight > 0) {
      C.relight -= dt;
      if (C.relight <= 0) {
        C.lit = 0.01;
        const p2 = U.v.copy(C.tip).applyMatrix4(U.cake.matrix);
        U.frame.toWorld(p2, p2);
        for (let k = 0; k < 6; k++) U.fx.spawn((__s2["x"] = p2.x, __s2["y"] = p2.y, __s2["z"] = p2.z, __s2["vx"] = (r() - 0.5) * 30, __s2["vy"] = 10 + r() * 20, __s2["life"] = 0.4, __s2["size"] = 0.7, __s2["size1"] = 0.1, __s2["r"] = 1, __s2["g"] = 0.8, __s2["b"] = 0.4, __s2["a"] = 1, __s2["cell"] = U.atlas.cell.spark, __s2["fadeIn"] = 0.05, __s2["fadeOut"] = 0.5, __s2));
      }
    }
    if (C.relight <= 0 && C.lit < 1) C.lit = Math.min(1, C.lit + dt * 3);
    const p = U.v.copy(C.tip).applyMatrix4(U.cake.matrix);
    U.frame.toWorld(p, p);
    if (C.lit > 0.02) {
      const f = 1 + Math.sin(t * 23 + C.ph) * 0.08 + Math.sin(t * 37 + C.ph * 2) * 0.05, L = C.lit;
      U.flames.spawn((__s3["x"] = p.x, __s3["y"] = p.y + 0.55 * L, __s3["z"] = p.z, __s3["life"] = 1, __s3["size"] = 1.25 * L * f, __s3["aspect"] = 1.6, __s3["r"] = 1, __s3["g"] = 0.62, __s3["b"] = 0.18, __s3["a"] = 0.95, __s3["cell"] = U.atlas.cell.flame, __s3["rot"] = Math.sin(t * 5 + C.ph) * 0.12, __s3["fadeIn"] = 0, __s3["fadeOut"] = 0, __s3));
      U.flames.spawn((__s4["x"] = p.x, __s4["y"] = p.y + 0.4 * L, __s4["z"] = p.z + 0.05, __s4["life"] = 1, __s4["size"] = 0.55 * L * f, __s4["aspect"] = 1.5, __s4["r"] = 1, __s4["g"] = 0.95, __s4["b"] = 0.8, __s4["a"] = 1, __s4["cell"] = U.atlas.cell.flame, __s4["fadeIn"] = 0, __s4["fadeOut"] = 0, __s4));
      U.flames.spawn((__s5["x"] = p.x, __s5["y"] = p.y + 0.5 * L, __s5["z"] = p.z - 0.1, __s5["life"] = 1, __s5["size"] = 3.2 * L, __s5["r"] = 1, __s5["g"] = 0.55, __s5["b"] = 0.2, __s5["a"] = 0.32, __s5["cell"] = U.atlas.cell.glow, __s5["fadeIn"] = 0, __s5["fadeOut"] = 0, __s5));
    } else if (C.smoke > 0) {
      C.smoke -= dt;
      if (r() < dt * 10) U.smoke.spawn((__s6["x"] = p.x, __s6["y"] = p.y + 0.2, __s6["z"] = p.z + 0.5, __s6["vx"] = (r() < 0.5 ? -1 : 1) * (3 + r() * 4), __s6["vy"] = 5 + r() * 3, __s6["vz"] = 3, __s6["life"] = 1.3, __s6["size"] = 0.7, __s6["size1"] = 2.4, __s6["r"] = 0.6, __s6["g"] = 0.6, __s6["b"] = 0.63, __s6["a"] = 0.38 * clamp(C.smoke), __s6["cell"] = U.atlas.cell.smoke, __s6["rot"] = r() * 6, __s6["spin"] = 1.2, __s6["wob"] = 3, __s6["wf"] = 3, __s6["fadeIn"] = 0.1, __s6["fadeOut"] = 0.7, __s6));
    }
  }
  U.flames.write();
  U.smoke.update(dt, U.down);
  U.fx.update(dt, U.down);
  U.conf.update(dt, U.down);
}
